package com.example.core

import com.example.model.Command
import com.example.model.FunctionDef
import com.example.model.Tool
import java.util.Locale

class GCodeGenerator(
    toolsList: List<Tool>,
    val variables: Map<String, Double>,
    val unrollLoops: Boolean = false,
    functionsList: List<FunctionDef> = emptyList(),
    val preamble: List<Command> = emptyList(),
    val postamble: List<Command> = emptyList()
) {
    val tools = toolsList.associateBy { it.number }
    var currentTool: Tool? = null
    val functions = functionsList.associateBy { it.name }
    val warnings = mutableListOf<String>()
    val glineToCmd = mutableMapOf<Int, Int>()
    val cmdToGLines = mutableMapOf<Int, MutableList<Int>>()

    private var fml = FormulaEval(variables)

    private fun n(v: Any?): Double = fml.resolveNumber(v)
    private fun i(v: Any?): Int = Math.round(n(v)).toInt()

    private fun emitLine(out: MutableList<String>, ref: IntArray, text: String, cmdIndex: Int) {
        out.add("N%04d %s".format(Locale.US, ref[0], text))
        if (cmdIndex >= 0) {
            val lineIdx = out.size - 1
            cmdToGLines.getOrPut(cmdIndex) { mutableListOf() }.add(lineIdx)
        }
        ref[0] += 10
    }

    fun generate(commands: List<Command>): List<String> {
        currentTool = null
        warnings.clear()
        glineToCmd.clear()
        cmdToGLines.clear()
        for (idx in commands.indices) {
            cmdToGLines[idx] = mutableListOf()
        }

        val liveVars = variables.toMutableMap()
        fml = FormulaEval(liveVars)

        val out = mutableListOf("%", "(generated by Mach3 G-Code Editor for Android)")
        val labels = mutableMapOf<String, Int>()
        for ((idx, c) in commands.withIndex()) {
            if (c.mnemonic == "LABEL") {
                val lname = c.params["name"]?.toString() ?: "L?"
                labels[lname] = (idx + 1) * 10
            }
        }

        val ref = intArrayOf(10)
        val state = doubleArrayOf(0.0, 0.0, 0.0) // cx, cy, cz
        val subPrograms = mutableMapOf<Int, List<String>>()
        var nextSubNum = 9000
        var curCmdIdx = -1

        fun emit(cmd: Command) {
            val m = cmd.mnemonic
            val p = cmd.params
            val idx = curCmdIdx

            when (m) {
                "#" -> {
                    val txt = p["text"]?.toString() ?: cmd.raw
                    out.add("($txt)")
                    if (idx >= 0) cmdToGLines.getOrPut(idx) { mutableListOf() }.add(out.size - 1)
                    return
                }
                "CALL_FUNC" -> {
                    val fnName = p["name"]?.toString() ?: ""
                    val mode = p["mode"]?.toString()?.lowercase(Locale.ROOT) ?: "inline"
                    val fn = functions[fnName]
                    if (fn == null) {
                        out.add("(CALL_FUNC $fnName: NOT FOUND)")
                        if (idx >= 0) cmdToGLines.getOrPut(idx) { mutableListOf() }.add(out.size - 1)
                        warnings.add("CALL_FUNC: функция $fnName не найдена")
                        return
                    }

                    val fnParams = mutableMapOf<String, Any>()
                    for (prm in fn.params) {
                        val pkey = "p_${prm.name}"
                        fnParams[prm.name] = p[pkey] ?: prm.defaultVal
                    }

                    if (mode == "m98") {
                        val num = nextSubNum++
                        val subLines = mutableListOf("O$num (function: $fnName)")
                        val subRef = intArrayOf(num * 100)

                        for (prm in fn.params) {
                            val v = n(fnParams[prm.name])
                            val full = "#FN_${fn.name}_${prm.name}"
                            subLines.add("N%04d %s = %s".format(Locale.US, subRef[0], full, v.toString()))
                            subRef[0] += 10
                            subLines.add("N%04d #%s = %s".format(Locale.US, subRef[0], prm.name, v.toString()))
                            subRef[0] += 10
                            liveVars[full] = v
                            liveVars["#" + prm.name] = v
                            liveVars[prm.name] = v
                        }
                        fml.vars = liveVars

                        emitBody(fn, fnParams, subLines, subRef, state)
                        subLines.add("N%04d M99".format(Locale.US, subRef[0]))
                        subPrograms[num] = subLines
                        emitLine(out, ref, "M98 P$num", idx)
                    } else {
                        emitLine(out, ref, "(CALL_FUNC $fnName inline begin)", idx)
                        emitBody(fn, fnParams, out, ref, state)
                        emitLine(out, ref, "(CALL_FUNC $fnName inline end)", idx)
                    }
                    return
                }
                "TOOL" -> {
                    val tNum = i(p["tool"] ?: 1)
                    val t = tools[tNum]
                    if (t == null) {
                        out.add("(TOOL $tNum NOT DEFINED)")
                        if (idx >= 0) cmdToGLines.getOrPut(idx) { mutableListOf() }.add(out.size - 1)
                        warnings.add("Инструмент T$tNum не найден в списке")
                    } else {
                        currentTool = t
                        emitLine(out, ref, "T${t.number} M6 (tool: ${t.name})", idx)
                        emitLine(out, ref, "S${t.rpm} M3", idx)
                    }
                    return
                }
                "SPIN" -> {
                    if (i(p["on"] ?: 1) != 0) {
                        val ccw = i(p["ccw"] ?: 0) != 0
                        val rpm = i(p["rpm"] ?: 8000)
                        emitLine(out, ref, "S$rpm M${if (ccw) "4" else "3"}", idx)
                    } else {
                        emitLine(out, ref, "M5", idx)
                    }
                    return
                }
                "COOL" -> {
                    val on = i(p["on"] ?: 1) != 0
                    val mist = i(p["mist"] ?: 0) != 0
                    val code = if (on) (if (mist) "M7" else "M8") else "M9"
                    emitLine(out, ref, code, idx)
                    return
                }
                "CLAMP" -> {
                    val on = i(p["on"] ?: 1) != 0
                    emitLine(out, ref, if (on) "M10" else "M11", idx)
                    return
                }
                "RAPID" -> {
                    val x = n(p["x"] ?: state[0])
                    val y = n(p["y"] ?: state[1])
                    val z = n(p["z"] ?: state[2])
                    val sb = StringBuilder("G0 X%.3f Y%.3f Z%.3f".format(Locale.US, x, y, z))
                    for (axis in listOf("a", "b", "c")) {
                        if (axis in p) sb.append(" %s%.3f".format(Locale.US, axis.uppercase(), n(p[axis])))
                    }
                    emitLine(out, ref, sb.toString(), idx)
                    state[0] = x; state[1] = y; state[2] = z
                    return
                }
                "FEED" -> {
                    val x = n(p["x"] ?: state[0])
                    val y = n(p["y"] ?: state[1])
                    val z = n(p["z"] ?: state[2])
                    val f = n(p["f"] ?: (currentTool?.feed ?: 200.0))
                    val sb = StringBuilder("G1 X%.3f Y%.3f Z%.3f".format(Locale.US, x, y, z))
                    for (axis in listOf("a", "b", "c")) {
                        if (axis in p) sb.append(" %s%.3f".format(Locale.US, axis.uppercase(), n(p[axis])))
                    }
                    sb.append(" F%.1f".format(Locale.US, f))
                    emitLine(out, ref, sb.toString(), idx)
                    state[0] = x; state[1] = y; state[2] = z
                    return
                }
                "ARC_CW", "ARC_CCW" -> {
                    val g = if (m == "ARC_CW") "G2" else "G3"
                    val x = n(p["x"] ?: state[0])
                    val y = n(p["y"] ?: state[1])
                    val z = n(p["z"] ?: state[2])
                    val ccx = n(p["cx"] ?: state[0])
                    val ccy = n(p["cy"] ?: state[1])
                    val f = n(p["f"] ?: (currentTool?.feed ?: 200.0))
                    val iOffset = ccx - state[0]
                    val jOffset = ccy - state[1]
                    emitLine(out, ref, "$g X%.3f Y%.3f Z%.3f I%.3f J%.3f F%.1f".format(Locale.US, x, y, z, iOffset, jOffset, f), idx)
                    state[0] = x; state[1] = y; state[2] = z
                    return
                }
                "DWELL" -> {
                    emitLine(out, ref, "G4 P%.3f".format(Locale.US, n(p["sec"] ?: 1.0)), idx)
                    return
                }
                "DRILL", "PECK", "CHIP", "BORE", "THREAD_R", "BORE_STD", "BORE_SPINDLE", "BORE_BACK", "BORE_MANUAL", "BORE_FINE" -> {
                    val g = when (m) {
                        "DRILL" -> "G81"
                        "PECK" -> "G83"
                        "CHIP" -> "G73"
                        "BORE" -> "G82"
                        "THREAD_R" -> "G84"
                        "BORE_STD" -> "G85"
                        "BORE_SPINDLE" -> "G86"
                        "BORE_BACK" -> "G87"
                        "BORE_MANUAL" -> "G88"
                        "BORE_FINE" -> "G89"
                        else -> "G81"
                    }
                    val x = n(p["x"] ?: state[0])
                    val y = n(p["y"] ?: state[1])
                    val z = n(p["z"] ?: -5.0)
                    val f = n(p["f"] ?: 60.0)
                    val r = n(p["r"] ?: 1.0)
                    emitLine(out, ref, "G0 X%.3f Y%.3f".format(Locale.US, x, y), idx)
                    emitLine(out, ref, "G0 Z%.3f".format(Locale.US, r), idx)
                    var extra = " R%.3f".format(Locale.US, r)
                    if (m in listOf("PECK", "CHIP")) {
                        extra += " Q%.3f".format(Locale.US, n(p["q"] ?: 1.0))
                    }
                    if (m in listOf("BORE", "THREAD_R", "BORE_MANUAL", "BORE_FINE")) {
                        extra += " P%.3f".format(Locale.US, n(p["p"] ?: 0.0))
                    }
                    emitLine(out, ref, "$g Z%.3f%s F%.1f".format(Locale.US, z, extra, f), idx)
                    emitLine(out, ref, "G80", idx)
                    emitLine(out, ref, "G0 Z5.000", idx)
                    state[0] = x; state[1] = y; state[2] = 5.0
                    return
                }
                "CANCEL" -> {
                    emitLine(out, ref, "G80", idx)
                    return
                }
                "POCKET_CW", "POCKET_CCW" -> {
                    val g = if (m == "POCKET_CW") "G12" else "G13"
                    val iVal = n(p["i"] ?: 10.0)
                    val jVal = n(p["j"] ?: 10.0)
                    val z = n(p["z"] ?: -2.0)
                    val f = n(p["f"] ?: 200.0)
                    emitLine(out, ref, "$g I%.3f J%.3f Z%.3f F%.1f".format(Locale.US, iVal, jVal, z, f), idx)
                    return
                }
                "PROBE" -> {
                    val x = n(p["x"] ?: state[0])
                    val y = n(p["y"] ?: state[1])
                    val z = n(p["z"] ?: state[2])
                    val f = n(p["f"] ?: 100.0)
                    emitLine(out, ref, "G31 X%.3f Y%.3f Z%.3f F%.1f".format(Locale.US, x, y, z, f), idx)
                    return
                }
                "WCS" -> {
                    val num = i(p["num"] ?: 54)
                    if (num in 54..59) {
                        emitLine(out, ref, "G$num", idx)
                    }
                    return
                }
                "G10" -> {
                    val l = i(p["l"] ?: 2)
                    val pp = i(p["p"] ?: 1)
                    val x = n(p["x"] ?: 0.0)
                    val y = n(p["y"] ?: 0.0)
                    val z = n(p["z"] ?: 0.0)
                    emitLine(out, ref, "G10 L$l P$pp X%.3f Y%.3f Z%.3f".format(Locale.US, x, y, z), idx)
                    return
                }
                "MACHINE" -> {
                    val x = n(p["x"] ?: state[0])
                    val y = n(p["y"] ?: state[1])
                    val z = n(p["z"] ?: state[2])
                    emitLine(out, ref, "G53 G0 X%.3f Y%.3f Z%.3f".format(Locale.US, x, y, z), idx)
                    state[0] = x; state[1] = y; state[2] = z
                    return
                }
                "G92SET" -> {
                    emitLine(out, ref, "G92 X%.3f Y%.3f Z%.3f".format(Locale.US, n(p["x"] ?: 0), n(p["y"] ?: 0), n(p["z"] ?: 0)), idx)
                    return
                }
                "SCALE_ON" -> {
                    emitLine(out, ref, "G51 X%.4f Y%.4f Z%.4f".format(Locale.US, n(p["x"] ?: 1), n(p["y"] ?: 1), n(p["z"] ?: 1)), idx)
                    return
                }
                "LOCAL_OFF" -> {
                    emitLine(out, ref, "G52 X%.3f Y%.3f Z%.3f".format(Locale.US, n(p["x"] ?: 0), n(p["y"] ?: 0), n(p["z"] ?: 0)), idx)
                    return
                }
                "ROT_ON" -> {
                    emitLine(out, ref, "G68 X%.3f Y%.3f R%.3f".format(Locale.US, n(p["x"] ?: 0), n(p["y"] ?: 0), n(p["angle"] ?: 0)), idx)
                    return
                }
                "CUTCOMP_L" -> { emitLine(out, ref, "G41 D${i(p["d"] ?: 1)}", idx); return }
                "CUTCOMP_R" -> { emitLine(out, ref, "G42 D${i(p["d"] ?: 1)}", idx); return }
                "TOOLCOMP_P" -> { emitLine(out, ref, "G43 H${i(p["h"] ?: 1)} Z%.3f".format(Locale.US, n(p["z"] ?: 0)), idx); return }
                "TOOLCOMP_M" -> { emitLine(out, ref, "G44 H${i(p["h"] ?: 1)}", idx); return }
                "STOP" -> { emitLine(out, ref, "M${if (i(p["optional"] ?: 0) != 0) "1" else "0"}", idx); return }
                "END" -> {
                    emitLine(out, ref, "M5", idx)
                    emitLine(out, ref, "M9", idx)
                    emitLine(out, ref, "G0 Z%.3f".format(Locale.US, maxOf(state[2], 5.0)), idx)
                    emitLine(out, ref, "M30", idx)
                    return
                }
                "SUB_CALL" -> {
                    emitLine(out, ref, "M98 P${i(p["name"] ?: 1000)} L${i(p["repeat"] ?: 1)}", idx)
                    return
                }
                "VAR" -> {
                    val name = p["name"]?.toString() ?: "#100"
                    val v = n(p["value"] ?: 0)
                    emitLine(out, ref, "$name = $v", idx)
                    liveVars[name] = v
                    fml.vars = liveVars
                    return
                }
                "VAR_ADD" -> {
                    val name = p["name"]?.toString() ?: "#100"
                    val delta = n(p["delta"] ?: 1)
                    emitLine(out, ref, "$name = [$name + $delta]", idx)
                    liveVars[name] = (liveVars[name] ?: 0.0) + delta
                    fml.vars = liveVars
                    return
                }
                "IF" -> {
                    val tgt = p["target"]?.toString() ?: "L1"
                    val targetLine = labels[tgt] ?: (ref[0] + 10)
                    val op = p["op"]?.toString()?.uppercase(Locale.ROOT) ?: "EQ"
                    val lhs = p["lhs"]?.toString() ?: "#100"
                    val rhs = n(p["rhs"] ?: 0)
                    emitLine(out, ref, "IF [$lhs $op $rhs] GOTO $targetLine", idx)
                    return
                }
                "GOTO" -> {
                    val tgt = p["target"]?.toString() ?: "L1"
                    val targetLine = labels[tgt] ?: (ref[0] + 10)
                    emitLine(out, ref, "GOTO $targetLine", idx)
                    return
                }
                "LABEL" -> {
                    val lname = p["name"]?.toString() ?: ""
                    out.add("(LABEL $lname -> N%04d)".format(Locale.US, (idx + 1) * 10))
                    if (idx >= 0) cmdToGLines.getOrPut(idx) { mutableListOf() }.add(out.size - 1)
                    return
                }
            }

            val simpleMap = mapOf(
                "PLANE_XY" to "G17", "PLANE_XZ" to "G18", "PLANE_YZ" to "G19",
                "UNITS_IN" to "G20", "UNITS_MM" to "G21",
                "ABS" to "G90", "INC" to "G91",
                "ARC_ABS" to "G90.1", "ARC_INC" to "G91.1",
                "FEED_INV" to "G93", "FEED_IPM" to "G94", "FEED_IPR" to "G95",
                "EXACT" to "G61", "SMOOTH" to "G64", "RET_INIT" to "G98", "RET_R" to "G99",
                "HOME" to "G28", "HOME2" to "G30", "HOME_BASE" to "G28.1",
                "POLAR_OFF" to "G15", "POLAR_ON" to "G16",
                "SCALE_OFF" to "G50", "ROT_OFF" to "G69", "CUTCOMP_OFF" to "G40",
                "TOOLCOMP_OFF" to "G49", "G92CLR" to "G92.1",
                "G92SUSP" to "G92.2", "G92RES" to "G92.3",
                "SUB_RET" to "M99", "REWIND" to "M47", "OVR_ON" to "M48", "OVR_OFF" to "M49"
            )
            simpleMap[m]?.let { code ->
                emitLine(out, ref, code, idx)
                return
            }

            out.add("(unknown $m)")
            if (idx >= 0) cmdToGLines.getOrPut(idx) { mutableListOf() }.add(out.size - 1)
        }

        // Preamble
        for (c in preamble) {
            curCmdIdx = -1
            emit(c)
        }

        if (!unrollLoops) {
            for ((idx, c) in commands.withIndex()) {
                curCmdIdx = idx
                try {
                    emit(c)
                } catch (e: Exception) {
                    warnings.add("${c.mnemonic}: ${e.message}")
                }
            }
        } else {
            val interp = ProgramInterp(commands, liveVars, maxSteps = 100000, functions = functions)
            interp.run { c, realIdx ->
                curCmdIdx = realIdx
                try {
                    emit(c)
                } catch (e: Exception) {
                    warnings.add("${c.mnemonic}: ${e.message}")
                }
            }
        }

        // Postamble
        for (c in postamble) {
            curCmdIdx = -1
            emit(c)
        }

        if (subPrograms.isNotEmpty()) {
            out.add("(----- subprograms -----)")
            for (key in subPrograms.keys.sorted()) {
                out.addAll(subPrograms[key]!!)
            }
        }

        out.add("%")

        glineToCmd.clear()
        for ((cidx, lines) in cmdToGLines) {
            for (li in lines) {
                glineToCmd[li] = cidx
            }
        }
        return out
    }

    private fun emitBody(fn: FunctionDef, params: Map<String, Any>, target: MutableList<String>, ref: IntArray, state: DoubleArray) {
        val fnLabels = mutableMapOf<String, Int>()
        val base = ref[0]
        for ((i, c) in fn.body.withIndex()) {
            if (c.mnemonic == "LABEL") {
                val nm = c.params["name"]?.toString() ?: ""
                fnLabels[nm] = base + i * 10
            }
        }
        for (prm in fn.params) {
            val v = n(params[prm.name])
            val full = "#FN_${fn.name}_${prm.name}"
            emitLine(target, ref, "$full = $v", -1)
            emitLine(target, ref, "#${prm.name} = $v", -1)
        }
        for (c in fn.body) {
            val m = c.mnemonic
            val p = c.params
            when (m) {
                "LABEL" -> {
                    val nm = p["name"]?.toString() ?: ""
                    emitLine(target, ref, "(LABEL _F${fn.name}_$nm)", -1)
                }
                "IF" -> {
                    val tgt = p["target"]?.toString() ?: ""
                    val tl = fnLabels[tgt] ?: (ref[0] + 10)
                    val op = p["op"]?.toString()?.uppercase(Locale.ROOT) ?: "EQ"
                    val lhs = p["lhs"]?.toString() ?: "#100"
                    val rhs = n(p["rhs"] ?: 0)
                    emitLine(target, ref, "IF [$lhs $op $rhs] GOTO $tl", -1)
                }
                "GOTO" -> {
                    val tgt = p["target"]?.toString() ?: ""
                    val tl = fnLabels[tgt] ?: (ref[0] + 10)
                    emitLine(target, ref, "GOTO $tl", -1)
                }
                "RAPID" -> {
                    val x = n(p["x"] ?: state[0])
                    val y = n(p["y"] ?: state[1])
                    val z = n(p["z"] ?: state[2])
                    emitLine(target, ref, "G0 X%.3f Y%.3f Z%.3f".format(Locale.US, x, y, z), -1)
                    state[0] = x; state[1] = y; state[2] = z
                }
                "FEED" -> {
                    val x = n(p["x"] ?: state[0])
                    val y = n(p["y"] ?: state[1])
                    val z = n(p["z"] ?: state[2])
                    val f = n(p["f"] ?: (currentTool?.feed ?: 200.0))
                    emitLine(target, ref, "G1 X%.3f Y%.3f Z%.3f F%.1f".format(Locale.US, x, y, z, f), -1)
                    state[0] = x; state[1] = y; state[2] = z
                }
                else -> {
                    // standard emit into target
                    // ...
                }
            }
        }
    }
}
