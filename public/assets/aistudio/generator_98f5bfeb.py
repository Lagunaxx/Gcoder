# -*- coding: utf-8 -*-
"""Генератор G-кода с картой соответствия псевдокод ↔ G-код."""

from gcode_editor.core.formula import FormulaEval
from gcode_editor.code.interpreter import ProgramInterp


class GCodeGenerator:
    def __init__(self, tools, variables, unroll_loops=False,
                 functions=None, preamble=None, postamble=None):
        self.tools = {t.number: t for t in tools}
        self.current_tool = None
        self.variables = variables
        self.fml = FormulaEval(variables)
        self.unroll_loops = unroll_loops
        self.functions = {f.name: f for f in (functions or [])}
        self.preamble = list(preamble or [])
        self.postamble = list(postamble or [])
        self.warnings = []
        self.gline_to_cmd = {}
        self.cmd_to_glines = {}

    def _n(self, v): return self.fml.resolve_number(v)
    def _i(self, v): return int(round(self._n(v)))

    def _emit(self, out, ref, text, cmd_index=-1, line_map=None):
        out.append(f"N{ref[0]:04d} {text}")
        if line_map is not None and cmd_index is not None and cmd_index >= 0:
            line_map[cmd_index].append(len(out) - 1)
        ref[0] += 10

    def generate(self, commands):
        self.current_tool = None
        self.warnings = []
        self.gline_to_cmd = {}
        self.cmd_to_glines = {i: [] for i in range(len(commands))}
        live_vars = dict(self.variables)
        self.fml = FormulaEval(live_vars)
        out = ["%", "(generated by GCodeEditor for Mach3)"]
        labels = {}
        for i, c in enumerate(commands):
            if c.mnemonic == "LABEL":
                labels[str(c.params.get("name", "L?"))] = (i + 1) * 10
        ref = [10]
        state = {"cx": 0.0, "cy": 0.0, "cz": 0.0}
        cache = {id(c): i for i, c in enumerate(commands)}
        sub_programs = {}
        next_sub_num = [9000]
        cur_cmd_idx = [-1]

        def emit(cmd):
            m, p = cmd.mnemonic, cmd.params
            idx = cur_cmd_idx[0]
            lm = self.cmd_to_glines if idx >= 0 else None

            if m == "#":
                out.append(f"({p.get('text','')})")
                if idx >= 0:
                    self.cmd_to_glines[idx].append(len(out) - 1)
                return
            if m == "CALL_FUNC":
                _emit_call(cmd, ref, force_inline=False); return
            if m == "TOOL":
                t = self.tools.get(self._i(p.get("tool", 1)))
                if not t:
                    out.append(f"(TOOL {p.get('tool')} NOT DEFINED)")
                    if idx >= 0:
                        self.cmd_to_glines[idx].append(len(out) - 1)
                    self.warnings.append(f"T{p.get('tool')} не найден")
                else:
                    self.current_tool = t
                    self._emit(out, ref, f"T{t.number} M6 (tool: {t.name})",
                               idx, lm)
                    self._emit(out, ref, f"S{t.rpm} M3", idx, lm)
                return
            if m == "SPIN":
                if self._i(p.get("on", 1)):
                    ccw = self._i(p.get("ccw", 0))
                    self._emit(out, ref,
                        f"S{self._i(p.get('rpm', 8000))} M{'4' if ccw else '3'}",
                        idx, lm)
                else:
                    self._emit(out, ref, "M5", idx, lm)
                return
            if m == "COOL":
                self._emit(out, ref,
                    f"M{'7' if self._i(p.get('mist', 0)) else '8'}"
                    if self._i(p.get("on", 1)) else "M9", idx, lm)
                return
            if m == "CLAMP":
                self._emit(out, ref,
                    f"M{10 if self._i(p.get('on', 1)) else 11}", idx, lm)
                return
            if m == "RAPID":
                x = self._n(p.get("x", state["cx"]))
                y = self._n(p.get("y", state["cy"]))
                z = self._n(p.get("z", state["cz"]))
                args = f"X{x:.3f} Y{y:.3f} Z{z:.3f}"
                for n in ("a","b","c"):
                    if n in p:
                        args += f" {n.upper()}{self._n(p[n]):.3f}"
                self._emit(out, ref, f"G0 {args}", idx, lm)
                state["cx"], state["cy"], state["cz"] = x, y, z
                return
            if m == "FEED":
                x = self._n(p.get("x", state["cx"]))
                y = self._n(p.get("y", state["cy"]))
                z = self._n(p.get("z", state["cz"]))
                f = self._n(p.get("f",
                    self.current_tool.feed if self.current_tool else 200))
                args = f"X{x:.3f} Y{y:.3f} Z{z:.3f}"
                for n in ("a","b","c"):
                    if n in p:
                        args += f" {n.upper()}{self._n(p[n]):.3f}"
                self._emit(out, ref, f"G1 {args} F{f:.1f}", idx, lm)
                state["cx"], state["cy"], state["cz"] = x, y, z
                return
            if m in ("ARC_CW", "ARC_CCW"):
                g = "G2" if m == "ARC_CW" else "G3"
                x = self._n(p.get("x", state["cx"]))
                y = self._n(p.get("y", state["cy"]))
                z = self._n(p.get("z", state["cz"]))
                ccx = self._n(p.get("cx", state["cx"]))
                ccy = self._n(p.get("cy", state["cy"]))
                f = self._n(p.get("f",
                    self.current_tool.feed if self.current_tool else 200))
                i = ccx - state["cx"]; j = ccy - state["cy"]
                self._emit(out, ref,
                    f"{g} X{x:.3f} Y{y:.3f} Z{z:.3f} "
                    f"I{i:.3f} J{j:.3f} F{f:.1f}", idx, lm)
                state["cx"], state["cy"], state["cz"] = x, y, z
                return
            if m == "DWELL":
                self._emit(out, ref, f"G4 P{self._n(p.get('sec',1)):.3f}",
                           idx, lm)
                return
            if m in ("DRILL","PECK","CHIP","BORE",
                    "THREAD_R","BORE_STD","BORE_SPINDLE",
                    "BORE_BACK","BORE_MANUAL","BORE_FINE"):
                g = {"DRILL":"G81","PECK":"G83","CHIP":"G73","BORE":"G82",
                     "THREAD_R":"G84","BORE_STD":"G85","BORE_SPINDLE":"G86",
                     "BORE_BACK":"G87","BORE_MANUAL":"G88","BORE_FINE":"G89"}[m]
                x = self._n(p.get("x", state["cx"]))
                y = self._n(p.get("y", state["cy"]))
                z = self._n(p.get("z", -5))
                f = self._n(p.get("f", 60))
                r = self._n(p.get("r", 1.0))
                self._emit(out, ref, f"G0 X{x:.3f} Y{y:.3f}", idx, lm)
                self._emit(out, ref, f"G0 Z{r:.3f}", idx, lm)
                extra = f" R{r:.3f}"
                if m in ("PECK", "CHIP"):
                    extra += f" Q{self._n(p.get('q',1.0)):.3f}"
                if m in ("BORE", "THREAD_R", "BORE_MANUAL", "BORE_FINE"):
                    extra += f" P{self._n(p.get('p',0.0)):.3f}"
                self._emit(out, ref, f"{g} Z{z:.3f}{extra} F{f:.1f}", idx, lm)
                self._emit(out, ref, "G80", idx, lm)
                self._emit(out, ref, "G0 Z5.000", idx, lm)
                state["cx"], state["cy"], state["cz"] = x, y, 5.0
                return
            if m == "CANCEL":
                self._emit(out, ref, "G80", idx, lm); return
            if m in ("POCKET_CW", "POCKET_CCW"):
                g = "G12" if m == "POCKET_CW" else "G13"
                i = self._n(p.get("i", 10.0))
                j = self._n(p.get("j", 10.0))
                z = self._n(p.get("z", -2.0))
                f = self._n(p.get("f", 200.0))
                self._emit(out, ref,
                    f"{g} I{i:.3f} J{j:.3f} Z{z:.3f} F{f:.1f}", idx, lm)
                return
            if m == "PROBE":
                x = self._n(p.get("x", state["cx"]))
                y = self._n(p.get("y", state["cy"]))
                z = self._n(p.get("z", state["cz"]))
                f = self._n(p.get("f", 100.0))
                self._emit(out, ref,
                    f"G31 X{x:.3f} Y{y:.3f} Z{z:.3f} F{f:.1f}", idx, lm)
                return

            simple = {
                "PLANE_XY":"G17","PLANE_XZ":"G18","PLANE_YZ":"G19",
                "UNITS_IN":"G20","UNITS_MM":"G21",
                "UNITS_IN2":"G70","UNITS_MM2":"G71",
                "ABS":"G90","INC":"G91",
                "ARC_ABS":"G90.1","ARC_INC":"G91.1",
                "FEED_INV":"G93","FEED_IPM":"G94","FEED_IPR":"G95",
                "EXACT":"G61","SMOOTH":"G64","RET_INIT":"G98","RET_R":"G99",
                "HOME":"G28","HOME2":"G30","HOME_BASE":"G28.1",
                "POLAR_OFF":"G15","POLAR_ON":"G16",
                "SCALE_OFF":"G50","ROT_OFF":"G69","CUTCOMP_OFF":"G40",
                "TOOLCOMP_OFF":"G49","G92CLR":"G92.1",
                "G92SUSP":"G92.2","G92RES":"G92.3",
                "REWIND":"M47","OVR_ON":"M48","OVR_OFF":"M49",
            }
            if m in simple:
                self._emit(out, ref, simple[m], idx, lm); return
            if m == "SUB_RET":
                self._emit(out, ref, "M99", idx, lm); return
            if m == "WCS":
                n = self._i(p.get("num", 54))
                if 54 <= n <= 59:
                    self._emit(out, ref, f"G{n}", idx, lm)
                return
            if m == "G10":
                l = self._i(p.get("l", 2))
                pp = self._i(p.get("p", 1))
                x = self._n(p.get("x", 0.0))
                y = self._n(p.get("y", 0.0))
                z = self._n(p.get("z", 0.0))
                self._emit(out, ref,
                    f"G10 L{l} P{pp} X{x:.3f} Y{y:.3f} Z{z:.3f}", idx, lm)
                return
            if m == "MACHINE":
                x = self._n(p.get("x", state["cx"]))
                y = self._n(p.get("y", state["cy"]))
                z = self._n(p.get("z", state["cz"]))
                self._emit(out, ref, f"G53 G0 X{x:.3f} Y{y:.3f} Z{z:.3f}",
                           idx, lm)
                state["cx"], state["cy"], state["cz"] = x, y, z
                return
            if m == "G92SET":
                self._emit(out, ref,
                    f"G92 X{self._n(p.get('x',0)):.3f} "
                    f"Y{self._n(p.get('y',0)):.3f} "
                    f"Z{self._n(p.get('z',0)):.3f}", idx, lm)
                return
            if m == "SCALE_ON":
                self._emit(out, ref,
                    f"G51 X{self._n(p.get('x',1)):.4f} "
                    f"Y{self._n(p.get('y',1)):.4f} "
                    f"Z{self._n(p.get('z',1)):.4f}", idx, lm)
                return
            if m == "LOCAL_OFF":
                self._emit(out, ref,
                    f"G52 X{self._n(p.get('x',0)):.3f} "
                    f"Y{self._n(p.get('y',0)):.3f} "
                    f"Z{self._n(p.get('z',0)):.3f}", idx, lm)
                return
            if m == "ROT_ON":
                self._emit(out, ref,
                    f"G68 X{self._n(p.get('x',0)):.3f} "
                    f"Y{self._n(p.get('y',0)):.3f} "
                    f"R{self._n(p.get('angle',0)):.3f}", idx, lm)
                return
            if m == "CUTCOMP_L":
                self._emit(out, ref, f"G41 D{self._i(p.get('d',1))}", idx, lm)
                return
            if m == "CUTCOMP_R":
                self._emit(out, ref, f"G42 D{self._i(p.get('d',1))}", idx, lm)
                return
            if m == "TOOLCOMP_P":
                self._emit(out, ref, f"G43 H{self._i(p.get('h',1))} "
                                     f"Z{self._n(p.get('z',0)):.3f}", idx, lm)
                return
            if m == "TOOLCOMP_M":
                self._emit(out, ref, f"G44 H{self._i(p.get('h',1))}", idx, lm)
                return
            if m == "CSS":
                self._emit(out, ref, f"G96 S{self._n(p.get('v',100)):.1f}",
                           idx, lm); return
            if m == "RPM_FIX":
                self._emit(out, ref, f"G97 S{self._i(p.get('rpm',8000))}",
                           idx, lm); return
            if m == "STOP":
                self._emit(out, ref,
                    f"M{1 if self._i(p.get('optional',0)) else 0}", idx, lm)
                return
            if m == "END":
                self._emit(out, ref, "M5", idx, lm)
                self._emit(out, ref, "M9", idx, lm)
                self._emit(out, ref, f"G0 Z{max(state['cz'], 5):.3f}", idx, lm)
                self._emit(out, ref, "M30", idx, lm)
                return
            if m == "SUB_CALL":
                self._emit(out, ref,
                    f"M98 P{self._i(p.get('name',1000))} "
                    f"L{self._i(p.get('repeat',1))}", idx, lm)
                return
            if m == "VAR":
                name = str(p.get("name", "#100"))
                try:
                    val = self._n(p.get("value", 0))
                    self._emit(out, ref, f"{name} = {val:g}", idx, lm)
                    live_vars[name] = val
                    self.fml.vars = live_vars
                except Exception as e:
                    self.warnings.append(f"VAR {name}: {e}")
                return
            if m == "VAR_ADD":
                name = str(p.get("name", "#100"))
                try:
                    d = self._n(p.get("delta", 1))
                    self._emit(out, ref, f"{name} = [{name} + {d:g}]", idx, lm)
                except Exception as e:
                    self.warnings.append(f"VAR_ADD {name}: {e}")
                return
            if m == "IF":
                tgt = str(p.get("target", "L1"))
                if tgt not in labels:
                    self.warnings.append(f"IF: метка {tgt} не найдена")
                tl = labels.get(tgt, ref[0] + 10)
                op = str(p.get("op", "EQ")).upper()
                if op not in ("EQ","NE","GT","LT","GE","LE"):
                    op = "EQ"
                lhs = str(p.get("lhs", "#100"))
                try:
                    rhs = self._n(p.get("rhs", 0))
                except Exception:
                    rhs = 0
                self._emit(out, ref, f"IF [{lhs} {op} {rhs:g}] GOTO {tl}",
                           idx, lm)
                return
            if m == "GOTO":
                tgt = str(p.get("target", "L1"))
                if tgt not in labels:
                    self.warnings.append(f"GOTO: метка {tgt} не найдена")
                tl = labels.get(tgt, ref[0] + 10)
                self._emit(out, ref, f"GOTO {tl}", idx, lm)
                return
            if m == "LABEL":
                cidx = cache.get(id(cmd), 0)
                out.append(f"(LABEL {p.get('name','')} -> N{(cidx+1)*10:04d})")
                if idx >= 0:
                    self.cmd_to_glines[idx].append(len(out) - 1)
                return
            out.append(f"(unknown {m})")
            if idx >= 0:
                self.cmd_to_glines[idx].append(len(out) - 1)

        def _emit_into(cmd, target, ref_obj):
            m, p = cmd.mnemonic, cmd.params
            if m == "RAPID":
                x = self._n(p.get("x", state["cx"]))
                y = self._n(p.get("y", state["cy"]))
                z = self._n(p.get("z", state["cz"]))
                self._emit(target, ref_obj, f"G0 X{x:.3f} Y{y:.3f} Z{z:.3f}",
                           -1, None)
                state["cx"], state["cy"], state["cz"] = x, y, z
                return
            if m == "FEED":
                x = self._n(p.get("x", state["cx"]))
                y = self._n(p.get("y", state["cy"]))
                z = self._n(p.get("z", state["cz"]))
                f = self._n(p.get("f",
                    self.current_tool.feed if self.current_tool else 200))
                self._emit(target, ref_obj,
                    f"G1 X{x:.3f} Y{y:.3f} Z{z:.3f} F{f:.1f}", -1, None)
                state["cx"], state["cy"], state["cz"] = x, y, z
                return
            saved_out = out[:]
            saved_ref = ref[0]
            out.clear()
            ref[0] = ref_obj[0]
            try:
                emit(cmd)
            finally:
                local_lines = out[:]
                out.clear()
                out.extend(saved_out)
                ref_obj[0] = ref[0]
                ref[0] = saved_ref
                target.extend(local_lines)

        def _emit_call(cmd, ref_here, force_inline=False):
            p = cmd.params
            fn_name = str(p.get("name", ""))
            mode = str(p.get("mode", "inline")).lower()
            if force_inline:
                mode = "inline"
            fn = self.functions.get(fn_name)
            if fn is None:
                out.append(f"(CALL_FUNC {fn_name}: not found)")
                if cur_cmd_idx[0] >= 0:
                    self.cmd_to_glines[cur_cmd_idx[0]].append(len(out) - 1)
                self.warnings.append(f"CALL_FUNC: функция {fn_name} не найдена")
                return
            params = {}
            for prm in fn.params:
                pkey = f"p_{prm.name}"
                params[prm.name] = p.get(pkey, prm.default)

            if mode == "m98":
                num = next_sub_num[0]
                next_sub_num[0] += 1
                sub_lines = [f"O{num} (function: {fn_name})"]
                sub_ref = [num * 100]
                for prm in fn.params:
                    val_raw = params[prm.name]
                    try:
                        val = self._n(val_raw)
                    except Exception:
                        val = 0.0
                    full = f"#FN_{fn.name}_{prm.name}"
                    sub_lines.append(f"N{sub_ref[0]:04d} {full} = {val:g}")
                    sub_ref[0] += 10
                    sub_lines.append(f"N{sub_ref[0]:04d} #{prm.name} = {val:g}")
                    sub_ref[0] += 10
                    live_vars[full] = val
                    live_vars["#" + prm.name] = val
                    live_vars[prm.name] = val
                self.fml.vars = live_vars
                _emit_body(fn, params, sub_lines, sub_ref)
                sub_lines.append(f"N{sub_ref[0]:04d} M99")
                sub_programs[num] = sub_lines
                self._emit(out, ref_here, f"M98 P{num}",
                           cur_cmd_idx[0], self.cmd_to_glines)
                return
            self._emit(out, ref_here,
                       f"(CALL_FUNC {fn_name} inline begin)",
                       cur_cmd_idx[0], self.cmd_to_glines)
            _emit_body(fn, params, out, ref_here)
            self._emit(out, ref_here,
                       f"(CALL_FUNC {fn_name} inline end)",
                       cur_cmd_idx[0], self.cmd_to_glines)

        def _emit_body(fn, params, target, ref_obj):
            prefix = f"_F{fn.name}_"
            fn_labels = {}
            base = ref_obj[0]
            virtual_line = {}
            for i, c in enumerate(fn.body):
                virtual_line[i] = base + i * 10
            for i, c in enumerate(fn.body):
                if c.mnemonic == "LABEL":
                    nm = str(c.params.get("name", ""))
                    fn_labels[nm] = virtual_line[i]
            for prm in fn.params:
                val_raw = params[prm.name]
                try:
                    val = self._n(val_raw)
                except Exception:
                    val = 0.0
                full = f"#FN_{fn.name}_{prm.name}"
                self._emit(target, ref_obj, f"{full} = {val:g}", -1, None)
                self._emit(target, ref_obj, f"#{prm.name} = {val:g}", -1, None)
                live_vars[full] = val
                live_vars["#" + prm.name] = val
                live_vars[prm.name] = val
            self.fml.vars = live_vars
            for i, c in enumerate(fn.body):
                m, p = c.mnemonic, c.params
                if m == "LABEL":
                    nm = str(p.get("name", ""))
                    self._emit(target, ref_obj, f"(LABEL {prefix}{nm})",
                               -1, None)
                    fn_labels[nm] = ref_obj[0] - 10
                    continue
                if m == "IF":
                    tgt = str(p.get("target", ""))
                    tl = fn_labels.get(tgt, ref_obj[0] + 10)
                    op = str(p.get("op", "EQ")).upper()
                    if op not in ("EQ","NE","GT","LT","GE","LE"):
                        op = "EQ"
                    lhs = str(p.get("lhs", "#100"))
                    try:
                        rhs = self._n(p.get("rhs", 0))
                    except Exception:
                        rhs = 0
                    self._emit(target, ref_obj,
                               f"IF [{lhs} {op} {rhs:g}] GOTO {tl}",
                               -1, None)
                    continue
                if m == "GOTO":
                    tgt = str(p.get("target", ""))
                    tl = fn_labels.get(tgt, ref_obj[0] + 10)
                    self._emit(target, ref_obj, f"GOTO {tl}", -1, None)
                    continue
                if m == "VAR":
                    name = str(p.get("name", "#100"))
                    try:
                        val = self._n(p.get("value", 0))
                        self._emit(target, ref_obj, f"{name} = {val:g}",
                                   -1, None)
                        live_vars[name] = val
                        self.fml.vars = live_vars
                    except Exception as e:
                        self.warnings.append(f"FUNC VAR {name}: {e}")
                    continue
                if m == "VAR_ADD":
                    name = str(p.get("name", "#100"))
                    try:
                        d = self._n(p.get("delta", 1))
                        self._emit(target, ref_obj,
                                   f"{name} = [{name} + {d:g}]", -1, None)
                        live_vars[name] = live_vars.get(name, 0.0) + d
                        self.fml.vars = live_vars
                    except Exception as e:
                        self.warnings.append(f"FUNC VAR_ADD {name}: {e}")
                    continue
                if m == "CALL_FUNC":
                    _emit_call(c, ref_obj, force_inline=True)
                    continue
                _emit_into(c, target, ref_obj)

        for c in self.preamble:
            try:
                emit(c)
            except Exception as e:
                out.append(f"(preamble error {c.mnemonic}: {e})")
                self.warnings.append(f"preamble {c.mnemonic}: {e}")

        if not self.unroll_loops:
            for i, c in enumerate(commands):
                cur_cmd_idx[0] = i
                try:
                    emit(c)
                except Exception as e:
                    out.append(f"(ошибка команды {c.mnemonic}: {e})")
                    self.warnings.append(f"{c.mnemonic}: {e}")
        else:
            def collect(c, idx):
                real_idx = -1
                for j, cc in enumerate(commands):
                    if cc is c:
                        real_idx = j
                        break
                cur_cmd_idx[0] = real_idx
                try:
                    emit(c)
                except Exception as e:
                    self.warnings.append(f"{c.mnemonic}: {e}")
            interp = ProgramInterp(commands, live_vars, max_steps=500000,
                                   functions=self.functions)
            interp.run(collect, 0)

        for c in self.postamble:
            try:
                emit(c)
            except Exception as e:
                out.append(f"(postamble error {c.mnemonic}: {e})")
                self.warnings.append(f"postamble {c.mnemonic}: {e}")

        if sub_programs:
            out.append("(----- subprograms -----)")
            for num in sorted(sub_programs.keys()):
                out.extend(sub_programs[num])

        out.append("%")

        self.gline_to_cmd = {}
        for cidx, lines in self.cmd_to_glines.items():
            for li in lines:
                self.gline_to_cmd[li] = cidx
        return out